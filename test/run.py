        pg.click('[data-start=A]'); pg.wait_for_timeout(800)
        pg.screenshot(path=OUT + '05_train_A.png', full_page=True)
        # focus rows (3D)
        pg.click('[data-focus="A.rows"]'); pg.wait_for_timeout(1500)
        pg.screenshot(path=OUT + '06_rows3d.png', full_page=False)
        print('canvas?', pg.evaluate('!!document.querySelector("#stage canvas")'))
        pg.click('#badbtn'); pg.wait_for_timeout(600)
        pg.click('[data-view=front]'); pg.wait_for_timeout(900)
        pg.locator('#focus').screenshot(path=OUT + '07_rows_bad_front.png')
        # go to pikepush, tick set -> rest + autoadvance
        pg.click('[data-focus="A.pikepush"]'); pg.wait_for_timeout(500)
        pg.click('#sets .srow[data-i="0"] [data-act=inc]'); pg.click('#sets .srow[data-i="0"] [data-act=tick]'); pg.wait_for_timeout(600)
        print('focus after tick:', pg.evaluate('__bold.state.active.focus'), 'rest visible:', pg.evaluate('!document.getElementById("restbar").hidden'))
        pg.screenshot(path=OUT + '08_after_tick.png', full_page=False)
        print('pikepush entry:', pg.evaluate('JSON.stringify(__bold.state.sessions["2026-11-05|A"].items["A.pikepush"])'))
        # history
        pg.click('[data-tab=hist]'); pg.wait_for_timeout(400)
        pg.screenshot(path=OUT + '09_hist.png', full_page=True)
        # plan editor
        pg.click('[data-tab=plan]'); pg.wait_for_timeout(400)
        pg.screenshot(path=OUT + '10_plan.png', full_page=True)
        pg.click('[data-dayd=A] > summary'); pg.wait_for_timeout(300)
        pg.screenshot(path=OUT + '10b_plan_open.png', full_page=True)
        pg.click('[data-act=add-item][data-day=A][data-b="0"]'); pg.wait_for_timeout(200)
        n = pg.evaluate('__bold.state.program.days[0].blocks[0].items.length'); print('items in A block0 after add:', n)
        print('A still open after add:', pg.evaluate('document.querySelector("[data-dayd=A]").open'))
        pg.click('[data-dayd=C] > summary'); pg.wait_for_timeout(200)
        pg.click('[data-act=del-day][data-day=C]'); pg.wait_for_timeout(200)
        print('confirm visible:', pg.evaluate('!!document.querySelector("[data-act=del-day-yes][data-day=C]")'))
