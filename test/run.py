        ctx2 = b.new_context(viewport={'width': 390, 'height': 844}, device_scale_factor=2, color_scheme='dark', is_mobile=True, has_touch=True)
        p2 = ctx2.new_page(); p2.goto('http://localhost:8765/'); p2.wait_for_timeout(900)
        p2.evaluate("""() => { const s = JSON.parse(localStorage.getItem('bold.v1')||'null'); }""")
