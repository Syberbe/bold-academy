        pg = ctx.new_page()
        errs = []
        pg.on('pageerror', lambda e: errs.append('PAGEERR ' + str(e)))
        pg.on('console', lambda m: errs.append(m.type + ': ' + m.text) if m.type in ('error', 'warning') else None)
        pg.goto('http://localhost:8765/'); pg.wait_for_timeout(1200)
        pg.screenshot(path=OUT + '01_today_empty.png', full_page=True)
        # import migration file
        pg.click('[data-tab=plan]'); pg.wait_for_timeout(300)
        pg.set_input_files('#imp', os.path.join(ROOT, 'test', 'fixture-logboek.json')); pg.wait_for_timeout(400)
        pg.screenshot(path=OUT + '02_import_box.png')
        pg.click('[data-act=imp-merge]'); pg.wait_for_timeout(300)
        print('sessions after import:', pg.evaluate('Object.keys(__bold.state.sessions).length'))
        pg.click('[data-tab=today]'); pg.wait_for_timeout(300)
        pg.screenshot(path=OUT + '03_today.png', full_page=True)
        print('plan:', json.dumps(pg.evaluate("__bold.plan('2026-11-05').occ.map(o=>[o.day,o.planned,o.status,o.eff])")))
