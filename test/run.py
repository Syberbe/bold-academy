        pg.click('[data-start=B]'); pg.wait_for_timeout(600)
        print('backfill active:', pg.evaluate('JSON.stringify(__bold.state.active)'), 'pastnote:', pg.evaluate('!!document.querySelector(".pastnote")'), 'wake-ind:', pg.evaluate('!!document.getElementById("wake-ind")'))
        mid = pg.evaluate('__bold.state.program.days.find(d=>d.id==="B").blocks[0].items[0].id')
        pg.click('[data-focus="' + mid + '"]'); pg.wait_for_timeout(400)
        pg.click('#sets .srow[data-i="0"] [data-act=tick]'); pg.wait_for_timeout(400)
        print('rest after past tick hidden:', pg.evaluate('document.getElementById("restbar").hidden'))
        pg.screenshot(path=OUT + '13_train_past.png', full_page=False)
        pg.click('#finish'); pg.wait_for_timeout(300)
        print('session 11-03 B:', pg.evaluate('!!__bold.state.sessions["2026-11-03|B"]'), 'route:', pg.evaluate('location.hash || document.querySelector("[aria-current=page]").dataset.tab'))
